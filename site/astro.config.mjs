// Astro configuration for the revkit review site.
//
// - Starlight is the docs shell (ADR-0001). Its i18n layer is configured with
//   English as the default locale (ADR-0019); no non-English locales ship in
//   v1, so `locales` stays undefined until we add one.
// - Solid is enabled as the island framework (ADR-0002); Starlight itself
//   uses Preact internally, so we pass `include` to Solid so it only
//   transforms our own islands.
// - Tailwind v4 comes in through `@tailwindcss/vite` per Starlight's own
//   `guides/css-and-tailwind` doc, and the base tokens are pulled from
//   `@astrojs/starlight-tailwind`.
// - `site` is set for absolute URLs in build output. Not the final review
//   host yet — hosted mode (ADR-0008) picks it up in M4.
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import solidJs from "@astrojs/solid-js";
import tailwindcss from "@tailwindcss/vite";
import { readdirSync } from "node:fs";
import { basename, dirname, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";
import remarkMath from "remark-math";
import { rehypeKatexStrict } from "./src/lib/rehype-katex-strict.ts";
import { rehypeDataSrc } from "../packages/cli/src/rehype-data-src.ts";

// Repo root — this file lives in `site/`, so the repo root is the
// parent directory. The rehype-data-src plugin rewrites every
// stamped block's `data-src` attribute as a repo-relative path so
// the rail can anchor comments to source lines (ADR-0006).
const REPO_ROOT = resolvePath(dirname(fileURLToPath(import.meta.url)), "..");

// Slug lists for the ADRs and design docs that live at the repo root (not
// under `src/content/docs/`). Starlight's autogenerated sidebar walks the
// filesystem and would miss files loaded by a custom loader, so the config
// enumerates them explicitly — a plain-string slug is Starlight's shorthand
// for a link whose label comes from the entry's title (ADR-0002 seeds this
// dogfood; M1 item 5 keeps the navigation stock — Starlight's sidebar plus
// its built-in prev/next, per the ADR-0001 2026-09-30 amendment).
function slugsFromRepoDir(dir) {
  return readdirSync(new URL(`../docs/${dir}/`, import.meta.url))
    .filter((name) => name.endsWith(".md"))
    .map((name) => `${dir}/${basename(name, ".md").toLowerCase()}`)
    .sort();
}
const designSlugs = slugsFromRepoDir("designs");
const adrSlugs = slugsFromRepoDir("adr");

export default defineConfig({
  site: "https://revkit.local",
  integrations: [
    starlight({
      title: "revkit",
      description: "HTML-first review surface for the agentic era.",
      // English-only in v1 (ADR-0019). Starlight's convention for a single-
      // language site is `locales: { root: {...} }`, which is the "i18n layer
      // configured for one locale" the ADR calls for — and avoids the
      // "collection i18n is empty" warning that fires when neither
      // `locales` nor `defaultLocale` is set.
      defaultLocale: "root",
      locales: {
        root: { label: "English", lang: "en" },
      },
      customCss: ["./src/styles/global.css"],
      // Every rendered code block (Expressive Code and Mermaid-as-code) is a
      // horizontally scrollable region, and WCAG 2.2 SC 2.1.1 (Keyboard,
      // ADR-0017) requires such a region to be reachable by keyboard. The
      // <pre> element is not tabbable on its own, so a small script adds
      // `tabindex=0` at load — a workaround Starlight and Expressive-Code
      // have not yet adopted upstream. Starlight `head` entries render the
      // exact tag given: no `type="module"` here means the browser executes
      // it inline (no Astro `is:inline` directive — that is a JSX-time
      // marker Starlight would emit as a literal HTML attribute).
      head: [
        {
          tag: "script",
          content:
            "document.addEventListener('DOMContentLoaded', function () { document.querySelectorAll('pre[data-language]').forEach(function (element) { element.tabIndex = 0; }); });",
        },
        // Self-hosted KaTeX stylesheet (ADR-0012 `font-src 'self'`, no CDN).
        // The assets are copied from `node_modules/katex/dist` to
        // `public/_katex/` by `scripts/copy-katex-assets.ts`, which
        // `bun run build` runs as `prebuild`. No client JS: math is
        // rendered to HTML at build by `rehype-katex` (ADR-0001, C5) and
        // this CSS + fonts is all the browser needs to display it.
        {
          tag: "link",
          attrs: {
            rel: "stylesheet",
            href: "/_katex/katex.min.css",
          },
        },
      ],
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/vig-os/revkit",
        },
      ],
      // The site dogfoods revkit's own documents (M1 item 2, issue #6): the
      // ADRs, the design and the feature matrix all render through the docs
      // collection, and the sidebar groups them so the shape mirrors what
      // review consumers of revkit will see. M1 item 5 (owner decision
      // 2026-09-30, ADR-0001 amendment) keeps navigation on Starlight's
      // stock sidebar + prev/next — the groups below are all config, no
      // component override; each group's ordered items also drive
      // Starlight's built-in `pagination` (prev/next links at the bottom
      // of every doc page, rendered at desktop and phone width).
      sidebar: [
        {
          label: "Start",
          items: [
            { label: "Overview", link: "/" },
            { label: "Math and plots", link: "/math-and-plots" },
          ],
        },
        {
          label: "Design",
          items: designSlugs,
        },
        {
          label: "ADRs",
          items: adrSlugs,
          collapsed: true,
        },
        {
          label: "Feature matrix",
          link: "/feature-matrix",
        },
      ],
    }),
    solidJs({
      include: ["**/packages/components/**", "**/src/islands/**"],
    }),
  ],
  // Math renders at build via `remark-math` (parses `$…$` / `$$…$$`) plus
  // the strict rehype-katex wrapper (`rehypeKatexStrict`), so no client
  // JS is shipped (ADR-0001 acceptance, C5). Configured on `markdown` —
  // the `@astrojs/mdx` integration extends `markdown` by default, so
  // MDX pages and the repo-docs loader's `ctx.renderMarkdown` path both
  // pick up the same plugin chain.
  //
  // `rehypeKatexStrict` promotes any KaTeX parse error into a thrown
  // build failure (rehype-katex on its own turns those into vfile
  // messages and ships a red `<span class="katex-error">` — see
  // src/lib/rehype-katex-strict.ts). `trust: false` (the default) blocks
  // `\href` and `\includegraphics`, so LaTeX cannot smuggle a link or an
  // external asset through math either.
  markdown: {
    remarkPlugins: [remarkMath],
    // `rehypeDataSrc` runs AFTER `rehype-katex-strict`: KaTeX rewrites
    // math regions to `<span class="katex">` trees WITHOUT position
    // info, so running the stamper after keeps it from stamping the
    // math internals with a garbage position. The stamper is a pure
    // walker (no I/O), so ordering is a semantics choice, not a
    // performance one.
    rehypePlugins: [
      [rehypeKatexStrict, { trust: false }],
      [rehypeDataSrc, { repoRoot: REPO_ROOT }],
    ],
  },
  vite: {
    plugins: [tailwindcss()],
  },
});
