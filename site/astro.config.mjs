// Astro configuration for the revkit review site.
//
// - Starlight is the docs shell (ADR-0001). Its i18n layer is configured with
//   English as the default locale (ADR-0019); no non-English locales ship in
//   v1, so `locales` stays undefined until we add one.
// - Solid is enabled as the island framework (ADR-0002); Starlight itself
//   uses Preact internally, so we pass `include` to Solid so it only
//   transforms our own islands.
// - Tailwind v4 comes in through `@tailwindcss/vite` per Starlight's own
//   `guides/css-and-tailwind` doc, and the base tokens are pulled from
//   `@astrojs/starlight-tailwind`.
// - `site` is set for absolute URLs in build output. Not the final review
//   host yet — hosted mode (ADR-0008) picks it up in M4.
import { defineConfig } from "astro/config";
import starlight from "@astrojs/starlight";
import solidJs from "@astrojs/solid-js";
import mdx from "@astrojs/mdx";
import tailwindcss from "@tailwindcss/vite";
import { existsSync, readdirSync, statSync } from "node:fs";
import { basename, dirname, join, resolve as resolvePath } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSharedMarkdownConfig } from "./src/lib/markdown-processor.ts";
import { readConsumerRoot } from "./src/lib/consumer-root.ts";

// Consumer-root mode (M5 part 2, issue #57): when `revkit build` sets
// `REVKIT_CONSUMER_ROOT`, this file is being run from the PACKAGED
// site to render an EXTERNAL repo's `docs/`. Absent, the file behaves
// exactly as it did before (revkit's own build renders its own tree).
const CONSUMER_ROOT = readConsumerRoot();

// Repo root — this file lives in `site/`, so the repo root is the
// parent directory. `rehype-data-src` uses it to rewrite every
// stamped block's `data-src` attribute as a repo-relative path so
// the rail can anchor comments to source lines (ADR-0006). In
// consumer mode the anchor root is the consumer repo, so the
// data-src attributes point at consumer paths.
//
// The Solid `include` glob below is intentionally NOT anchored at
// REPO_ROOT — during a `revkit review` safe build this config is
// loaded from the sandbox, where REPO_ROOT resolves to the sandbox
// root, and Vite still loads `@revkit/components` through the
// TRUSTED checkout's node_modules symlink (outside the sandbox).
// An anchored include would miss that real path and Solid would
// skip transforming Callout / Aside / …. The unanchored include
// plus a `.revkit-review/` exclude gives us both: the trusted copy
// is still matched, and the sandbox copy is never transformed.
const REPO_ROOT =
  CONSUMER_ROOT ?? resolvePath(dirname(fileURLToPath(import.meta.url)), "..");

// Slug lists for the ADRs and design docs that live at the repo root (not
// under `src/content/docs/`). Starlight's autogenerated sidebar walks the
// filesystem and would miss files loaded by a custom loader, so the config
// enumerates them explicitly — a plain-string slug is Starlight's shorthand
// for a link whose label comes from the entry's title (ADR-0002 seeds this
// dogfood; M1 item 5 keeps the navigation stock — Starlight's sidebar plus
// its built-in prev/next, per the ADR-0001 2026-09-30 amendment).
function slugsFromRepoDir(dir) {
  return readdirSync(new URL(`../docs/${dir}/`, import.meta.url))
    .filter((name) => name.endsWith(".md"))
    .map((name) => `${dir}/${basename(name, ".md").toLowerCase()}`)
    .sort();
}

// Walk consumer's `docs/` (absolute) and emit Starlight sidebar
// entries in consumer mode: each top-level directory becomes a
// group label, each markdown file under one becomes a link item
// under that group. This mirrors what
// `slugsFromRepoDir` does for revkit's own build, but without
// hard-coded `adr/` and `designs/` subdirs — consumers name their
// tree freely, and the sidebar reflects it (M5 part 2 sidebar
// decision, DESIGN-0002 §5 update: enumerate to keep the docs
// collection loader and the sidebar coherent, since Starlight's
// autogenerate walks `src/content/docs/` directly and misses
// content collections that load from elsewhere).
function buildConsumerSidebar(consumerDocsDir) {
  if (!existsSync(consumerDocsDir)) return [];
  const items = [];
  const rootFiles = [];
  for (const entry of readdirSync(consumerDocsDir).sort()) {
    const abs = join(consumerDocsDir, entry);
    let st;
    try {
      st = statSync(abs);
    } catch {
      continue;
    }
    if (st.isFile()) {
      if (!/\.(md|mdx)$/i.test(entry)) continue;
      const slug = basename(entry).replace(/\.(md|mdx)$/i, "").toLowerCase();
      // `index.md(x)` → the root of the collection. Starlight
      // wants an EMPTY string as the slug (no leading `/`), not
      // `/` and not `index`; both throw at build time.
      if (slug === "index") {
        rootFiles.push("");
      } else {
        rootFiles.push(slug);
      }
    } else if (st.isDirectory()) {
      const subEntries = readdirSync(abs).sort()
        .filter((f) => /\.(md|mdx)$/i.test(f))
        .map((f) => `${entry}/${basename(f).replace(/\.(md|mdx)$/i, "").toLowerCase()}`);
      if (subEntries.length > 0) {
        // Directory label = the dir name (unmodified — consumers pick it).
        items.push({ label: entry, items: subEntries, collapsed: false });
      }
    }
  }
  if (rootFiles.length > 0) {
    items.unshift({ label: "Docs", items: rootFiles });
  }
  return items;
}

// In consumer mode revkit's own ADR / design lists are absent. In
// own-repo mode this stays exactly the pre-#57 value.
const designSlugs = CONSUMER_ROOT ? [] : slugsFromRepoDir("designs");
const adrSlugs = CONSUMER_ROOT ? [] : slugsFromRepoDir("adr");

// Sidebar shape: consumer mode enumerates their `docs/`; own-repo
// mode keeps the shipped groups (Start / Design / ADRs / Matrix)
// unchanged.
const CONSUMER_SIDEBAR = CONSUMER_ROOT
  ? buildConsumerSidebar(join(CONSUMER_ROOT, "docs"))
  : null;

// Vite cache override — `revkit build` points these at
// `<consumer>/.revkit/cache/vite` so the nix store's read-only
// `<packagedSite>/node_modules/.vite/` is never touched.
const VITE_CACHE_DIR = (process.env.REVKIT_VITE_CACHE_DIR ?? "").trim() || undefined;
// Astro cache override — `revkit build` points this at
// `<consumer>/.revkit/cache/astro` for the same reason.
const ASTRO_CACHE_DIR = (process.env.REVKIT_ASTRO_CACHE_DIR ?? "").trim() || undefined;

export default defineConfig({
  site: "https://revkit.local",
  integrations: [
    starlight({
      title: "revkit",
      description: "HTML-first review surface for the agentic era.",
      // English-only in v1 (ADR-0019). Starlight's convention for a single-
      // language site is `locales: { root: {...} }`, which is the "i18n layer
      // configured for one locale" the ADR calls for — and avoids the
      // "collection i18n is empty" warning that fires when neither
      // `locales` nor `defaultLocale` is set.
      defaultLocale: "root",
      locales: {
        root: { label: "English", lang: "en" },
      },
      customCss: ["./src/styles/global.css"],
      // Every rendered code block (Expressive Code and Mermaid-as-code) is a
      // horizontally scrollable region, and WCAG 2.2 SC 2.1.1 (Keyboard,
      // ADR-0017) requires such a region to be reachable by keyboard. The
      // <pre> element is not tabbable on its own, so a small script adds
      // `tabindex=0` at load — a workaround Starlight and Expressive-Code
      // have not yet adopted upstream. Starlight `head` entries render the
      // exact tag given: no `type="module"` here means the browser executes
      // it inline (no Astro `is:inline` directive — that is a JSX-time
      // marker Starlight would emit as a literal HTML attribute).
      head: [
        {
          tag: "script",
          content:
            "document.addEventListener('DOMContentLoaded', function () { document.querySelectorAll('pre[data-language]').forEach(function (element) { element.tabIndex = 0; }); });",
        },
        // Self-hosted KaTeX stylesheet (ADR-0012 `font-src 'self'`, no CDN).
        // The assets are copied from `node_modules/katex/dist` to
        // `public/_katex/` by `scripts/copy-katex-assets.ts`, which
        // `bun run build` runs as `prebuild`. No client JS: math is
        // rendered to HTML at build by `rehype-katex` (ADR-0001, C5) and
        // this CSS + fonts is all the browser needs to display it.
        {
          tag: "link",
          attrs: {
            rel: "stylesheet",
            href: "/_katex/katex.min.css",
          },
        },
      ],
      social: [
        {
          icon: "github",
          label: "GitHub",
          href: "https://github.com/vig-os/revkit",
        },
      ],
      // The site dogfoods revkit's own documents (M1 item 2, issue #6): the
      // ADRs, the design and the feature matrix all render through the docs
      // collection, and the sidebar groups them so the shape mirrors what
      // review consumers of revkit will see. M1 item 5 (owner decision
      // 2026-09-30, ADR-0001 amendment) keeps navigation on Starlight's
      // stock sidebar + prev/next — the groups below are all config, no
      // component override; each group's ordered items also drive
      // Starlight's built-in `pagination` (prev/next links at the bottom
      // of every doc page, rendered at desktop and phone width).
      sidebar: CONSUMER_SIDEBAR ?? [
        {
          label: "Start",
          items: [
            { label: "Overview", link: "/" },
            { label: "Math and plots", link: "/math-and-plots" },
          ],
        },
        {
          label: "Design",
          items: designSlugs,
        },
        {
          label: "ADRs",
          items: adrSlugs,
          collapsed: true,
        },
        {
          label: "Feature matrix",
          link: "/feature-matrix",
        },
      ],
    }),
    // Explicit `@astrojs/mdx` in consumer mode. Starlight
    // auto-adds it via `integrations.push(mdx(...))` from its
    // `astro:config:setup` hook, but in the packaged flow the
    // `astro:config:setup` cascade sometimes registers the
    // pushed integration too late for the FIRST content-sync
    // pass — Starlight's docs loader logs
    // `[starlight-docs-loader] No entry type found for
    // index.mdx` and the docs collection ends up empty. An
    // explicit integration entry participates in the first
    // pass, so `.mdx` is on `contentEntryTypes` before the
    // docs collection loads. Own-repo mode leaves this alone
    // — the auto-add there works from the FIRST pass because
    // the astro toolchain is loaded from the same
    // node_modules the config is loaded from. (Not fully
    // pinned down, worth a follow-up upstream.)
    ...(CONSUMER_ROOT ? [mdx({ optimize: true })] : []),
    solidJs({
      // Solid transforms every `.tsx` under `packages/components/`
      // (the components package) and `site/src/islands/` (the site's
      // own islands). The `exclude` guard drops any path inside a
      // `site/.revkit-review/…/` sandbox, so a hostile PR whose
      // materialised tree happens to sit under that path (see
      // `fetch-pr.ts:reviewTargetDir`) can never have a smuggled
      // `.tsx` transformed by the reviewer's Solid pass. The
      // reviewer's real build reads `@revkit/components` through
      // node_modules resolution against the TRUSTED checkout, so
      // the include still matches and Callout / Aside / … keep
      // being transformed.
      include: [
        "**/packages/components/**",
        "**/site/src/islands/**",
        // Consumer-mode packaged build: with vite's
        // `resolve.preserveSymlinks: true`, `<staging>/node_
        // modules/@revkit/components/src/Callout.tsx` is
        // reported by that path — the previous `packages/
        // components/**` glob does not match. Add the
        // node-module path so Solid still transforms Callout /
        // Aside / … in the packaged flow. Own-repo mode also
        // uses this path when `@revkit/components` is resolved
        // through node_modules (harmless duplication).
        "**/node_modules/@revkit/components/**",
      ],
      exclude: ["**/site/.revkit-review/**"],
    }),
  ],
  // Math renders at build via `remark-math` (parses `$…$` / `$$…$$`) plus
  // the strict rehype-katex wrapper (`rehypeKatexStrict`), so no client
  // JS is shipped (ADR-0001 acceptance, C5). Configured on `markdown` —
  // the `@astrojs/mdx` integration extends `markdown` by default, so
  // MDX pages and the repo-docs loader's `ctx.renderMarkdown` path both
  // pick up the same plugin chain.
  //
  // `rehypeKatexStrict` promotes any KaTeX parse error into a thrown
  // build failure (rehype-katex on its own turns those into vfile
  // messages and ships a red `<span class="katex-error">` — see
  // src/lib/rehype-katex-strict.ts). `trust: false` (the default) blocks
  // `\href` and `\includegraphics`, so LaTeX cannot smuggle a link or an
  // external asset through math either.
  // The remark + rehype list comes from ONE shared module that the
  // daemon's fast-path publish also imports (M2 item 9, story A4).
  // A new plugin lands in ONE place; both consumers see it.
  markdown: buildSharedMarkdownConfig(REPO_ROOT, {
    pathMap: CONSUMER_ROOT
      ? [{
          from: join(CONSUMER_ROOT, ".revkit", "build", "src", "content", "docs"),
          to: join(CONSUMER_ROOT, "docs"),
        }]
      : undefined,
  }),
  // `cacheDir` — astro's default is `./node_modules/.astro`. In the
  // packaged CLI's flow that would land INSIDE the read-only nix
  // store, so `revkit build` sets `REVKIT_ASTRO_CACHE_DIR` to a
  // path under `<consumer>/.revkit/cache/`. Own-repo build leaves
  // it undefined and astro uses its default (working, writable).
  ...(ASTRO_CACHE_DIR ? { cacheDir: ASTRO_CACHE_DIR } : {}),
  vite: {
    plugins: [tailwindcss()],
    // Same story for vite as for astro's own cacheDir above.
    // `revkit build` sets `REVKIT_VITE_CACHE_DIR` and vite writes
    // its dep cache there instead of `./node_modules/.vite/`
    // (which is inside the read-only packaged site in the
    // packaged flow). Own-repo mode leaves it undefined.
    ...(VITE_CACHE_DIR ? { cacheDir: VITE_CACHE_DIR } : {}),
    // Consumer mode: node_modules at `<staging>/node_modules/`
    // is a real dir with per-entry symlinks to the packaged
    // deps (in `/nix/store/...`). Astro's `normalizeFilename`
    // uses `commonAncestorPath` to decide whether a module
    // file is "in root" — a `/nix/store/...` path shares no
    // ancestor with `<staging>` and gets its filename
    // concatenated to the root (`<staging>/nix/store/...`),
    // which is broken. We keep vite reporting the STAGING path
    // for every dep so `isPathInRoot` always returns true.
    //
    // `preserveSymlinks: true` — vite reports the symlink path
    // (inside `<staging>`), not the resolved physical path.
    // Paired with `NODE_PRESERVE_SYMLINKS=1` in the child env
    // (set by `revkit build`) so astro's own `require.resolve`
    // (via `createRequire`) also stays on staging paths.
    ...(CONSUMER_ROOT
      ? {
          resolve: {
            preserveSymlinks: true,
            // With preserveSymlinks, vite's own dedupe defaults
            // don't find astro through the symlink chain —
            // dedupe on the packages astro's runtime pulls in
            // twice otherwise.
            dedupe: ["astro", "@astrojs/starlight", "@astrojs/mdx"],
          },
          // Ignore watching of `<staging>/node_modules/` — the
          // symlink entries resolve into a read-only nix-store
          // path, and chokidar's default walk would try to
          // watch every file under it. Never triggered by
          // `astro build`, but future-proofs `astro dev`.
          server: { watch: { ignored: ["**/node_modules/**"] } },
        }
      : {}),
  },
});
